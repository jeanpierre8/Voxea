func check(_ condition: Bool, _ label: String) { precondition(condition, label); print("PASS \(label)") }
var gate = AudioSessionGate()
let first = gate.begin()
check(!gate.acceptingAudio, "Startup cannot append audio before activation")
check(gate.activate(first) && gate.acceptingAudio, "Current recording can accept audio")
gate.stop()
check(!gate.acceptingAudio, "Key release rejects late audio callbacks")
check(!gate.activate(first), "Cancelled startup cannot reactivate recording")
let second = gate.begin()
check(gate.activate(second), "Following recording starts normally")
check(!gate.stop(expectedGeneration: first), "Old startup completion cannot stop newer recording")
check(gate.acceptingAudio, "New recording survives stale cleanup")
check(gate.stop(expectedGeneration: second) && !gate.acceptingAudio, "Matching cleanup stops its own recording")
let cancelledStart = gate.begin()
gate.stop()
let newerStart = gate.begin()
check(!gate.activate(cancelledStart), "Older queued startup is rejected")
check(gate.activate(newerStart), "Newest queued startup remains usable")
