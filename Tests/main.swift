func check(_ value: @autoclosure () -> Bool, _ label: String) {
    precondition(value(), label)
    print("PASS " + label)
}
var hold = KeyState()
check(hold.event(down: false, toggle: false) == nil, "Unmatched release ignored")
check(hold.event(down: true, toggle: false) == .start, "Hold starts")
check(hold.event(down: true, toggle: false) == nil, "Repeat ignored")
check(hold.event(down: false, toggle: false) == .stop, "Release stops")
check(hold.event(down: false, toggle: false) == nil, "Duplicate release ignored")
var toggle = KeyState()
check(toggle.event(down: true, toggle: true) == .start, "Toggle starts")
check(toggle.event(down: false, toggle: true) == nil && toggle.recording, "Toggle continues after release")
check(toggle.event(down: true, toggle: true) == .stop, "Second press stops")
check(toggle.event(down: true, toggle: true) == nil, "Stop repeat ignored")
_ = toggle.event(down: false, toggle: true)
check(toggle.event(down: true, toggle: true) == .start, "Toggle restarts")
var cancelled = KeyState()
_ = cancelled.event(down: true, toggle: false)
cancelled.cancel()
check(cancelled.event(down: false, toggle: false) == nil, "Cancel then release does not finalize")
check(cancelled.event(down: true, toggle: false) == .start, "Can restart after cancellation")
print("12 checks passed")
